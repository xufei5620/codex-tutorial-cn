// Small helpers shared by the build steps. No network, shell or deployment.
import fs from 'node:fs'
import path from 'node:path'

export const esc = (value) =>
  String(value ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c])

export const plain = (value) =>
  String(value ?? '')
    .replace(/<[^>]*>/g, ' ')
    .replace(/&[^;]+;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

export const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'))

// Marks every generated page. The text is part of the published HTML and search data.
export const GEN = '<!-- generated by build/index.mjs; edit shared/pages, or pages/ and overrides/ in the site folder -->\n'

export function markGenerated(text) {
  const normalized = text.replace(/^﻿/, '').replace(/\r\n/g, '\n')
  if (!normalized.startsWith('---\n')) return GEN + normalized
  const fm = normalized.match(/^---\n[\s\S]*?\n---(?:\n|$)/)
  if (!fm) throw Error('Invalid frontmatter')
  return fm[0].trimEnd() + '\n' + GEN + normalized.slice(fm[0].length)
}

export function render(text, vars) {
  const result = text.replace(/%%([A-Z_]+)%%/g, (token, key) => (Object.hasOwn(vars, key) ? String(vars[key]) : token))
  const missing = result.match(/%%[A-Z_]+%%/g)
  if (missing) throw Error('Unresolved variables: ' + [...new Set(missing)].join(', '))
  return result
}

export function https(value, label) {
  const url = new URL(value)
  if (url.protocol !== 'https:' || url.username || url.password) throw Error(label + ': expected HTTPS URL without credentials')
  return url.href
}

/** Relative paths of every file below `dir`, depth first with each directory's entries in name order. */
export function listFiles(dir, base = dir) {
  if (!fs.existsSync(dir)) return []
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .flatMap((entry) => {
      if (entry.isSymbolicLink()) throw Error('Symlinks are not supported: ' + entry.name)
      const full = path.join(dir, entry.name)
      return entry.isDirectory() ? listFiles(full, base) : [path.relative(base, full)]
    })
}

/** Writes below `root` only; refuses absolute paths and `..`. */
export function writeBelow(root, name, body) {
  if (path.isAbsolute(name) || name.split(/[\\/]/).includes('..')) throw Error('Invalid output path: ' + name)
  const target = path.join(root, name)
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, body)
}

export function copyTree(from, to, accept = () => true) {
  for (const name of listFiles(from)) {
    if (!accept(name)) continue
    const target = path.join(to, name)
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.copyFileSync(path.join(from, name), target)
  }
}
